#!/usr/bin/env python3
"""Turn icons/apple-touch-icon.png (180x180, iOS home screen) and icons/icon-192.png into icons.h (PROGMEM arrays)."""
import os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = ["// icons.h - generated by tools/embed_icons.py from icons/*.png. Do not edit.", "#pragma once", "#include <stddef.h>", "#include <stdint.h>", ""]
for fname, sym in (("apple-touch-icon.png", "ICON_180"), ("icon-192.png", "ICON_192")):
    data = open(os.path.join(root, "icons", fname), "rb").read()
    assert data[:8] == b"\x89PNG\r\n\x1a\n", fname
    rows = ["  " + ",".join("0x%02x" % b for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    out.append("static const size_t %s_LEN = %d;" % (sym, len(data)))
    out.append("static const uint8_t %s[] PROGMEM = {\n%s\n};\n" % (sym, ",\n".join(rows)))
open(os.path.join(root, "icons.h"), "w").write("\n".join(out))
print("icons.h written")
